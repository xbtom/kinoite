#!/bin/bash

# Installs the NVIDIA Container Toolkit so that Podman (and distrobox) containers
# can use the GPU through CDI, and arranges for the CDI specification to be
# generated automatically on the host.
#
# The CDI specification describes the GPU device nodes and driver libraries of
# the machine it is generated on, so it cannot be produced while the image is
# built (the build container has no GPU and no loaded driver). Since toolkit
# 1.18 the package ships the nvidia-cdi-refresh.{path,service} units, which
# write /var/run/cdi/nvidia.yaml on every boot and again whenever the driver or
# the toolkit changes, so nothing has to be generated by hand after an image
# update.
#
# Design notes:
# - The toolkit comes from NVIDIA's own repository. Fedora's
#   golang-github-nvidia-container-toolkit package is older than 1.18 and does
#   not ship the refresh units.
# - Only nvidia-container-toolkit-base is installed. It contains nvidia-ctk, the
#   CDI hook and the refresh units, which is everything CDI needs. The full
#   nvidia-container-toolkit package also installs the legacy runtime hook
#   (oci-nvidia-hook.json), which NVIDIA documents as conflicting with CDI for
#   containers that set NVIDIA_VISIBLE_DEVICES. Change PACKAGES below if the
#   legacy hook is ever needed.
# - The package scriptlets only touch systemd when it is running, which is never
#   the case inside an image build, so the units are enabled explicitly here
#   and verified afterwards.
#
# Responsibility: install the NVIDIA Container Toolkit and enable CDI refresh only.

set -euo pipefail

REPO_URL="https://nvidia.github.io/libnvidia-container/stable/rpm/nvidia-container-toolkit.repo"
REPO_FILE="/etc/yum.repos.d/nvidia-container-toolkit.repo"

# The nvidia-cdi-refresh units first shipped in toolkit 1.18.0.
MIN_VERSION="1.18.0"
PACKAGES=(nvidia-container-toolkit-base)
CDI_UNITS=(nvidia-cdi-refresh.path nvidia-cdi-refresh.service)

ATTEMPTS=3

die() {
    echo "ERROR: $*" >&2
    exit 1
}

# The repository is served from GitHub Pages; retry with a short backoff so a
# single transient network error does not fail the whole image build.
retry() {
    local attempt
    for ((attempt = 1; attempt <= ATTEMPTS; attempt++)); do
        if "$@"; then
            return 0
        fi
        if ((attempt < ATTEMPTS)); then
            echo "Attempt ${attempt}/${ATTEMPTS} failed: $*" >&2
            sleep $((attempt * 10))
        fi
    done
    return 1
}

# The repository is only needed while building; do not ship it in the image.
trap 'rm -f "${REPO_FILE}"' EXIT

echo "Adding the NVIDIA Container Toolkit repository..."
retry curl --fail --silent --show-error --location \
    --output "${REPO_FILE}" "${REPO_URL}" ||
    die "could not download ${REPO_URL}"
grep -q '^\[nvidia-container-toolkit\]' "${REPO_FILE}" ||
    die "${REPO_FILE} does not define the nvidia-container-toolkit repository"

echo "Installing ${PACKAGES[*]}..."
retry dnf5 install -y "${PACKAGES[@]}" ||
    die "could not install ${PACKAGES[*]}"

# Guard against silently ending up with a toolkit that has no refresh units
# (e.g. an older build from another repository).
version="$(rpm -q --qf '%{VERSION}\n' nvidia-container-toolkit-base)"
echo "Installed nvidia-container-toolkit-base ${version}"
printf '%s\n' "${MIN_VERSION}" "${version}" | sort -V -C ||
    die "nvidia-container-toolkit-base ${version} is older than ${MIN_VERSION} and has no CDI refresh units"

echo "Enabling the CDI refresh units..."
systemctl enable "${CDI_UNITS[@]}"
for unit in "${CDI_UNITS[@]}"; do
    [[ "$(systemctl is-enabled "${unit}")" == "enabled" ]] ||
        die "${unit} is not enabled"
done

echo "NVIDIA Container Toolkit installed; the CDI specification is generated at boot (/var/run/cdi/nvidia.yaml)."
